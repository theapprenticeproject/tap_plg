        """Get statistics about detection capabilities."""
        return {
            "detection_methods": [
                "metadata_analysis",
                "statistical_analysis",
                "noise_pattern_analysis",
            ],
            "ai_platforms_tracked": len(self.ai_platforms),
            "requires_scipy": True,  # For advanced analysis
        }
